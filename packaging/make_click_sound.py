#!/usr/bin/env python3
"""Generate the original quiet mechanical tally click and its embedded PCM/WAV."""
from pathlib import Path
import io
import math
import random
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
RATE = 48000
LENGTH = 0.035
PEAK = 0.065


def main():
    noise = random.Random(0x54414C4C59)
    fast = slow = 0.0
    high = 1 - math.exp(-2 * math.pi * 2400 / RATE)
    low = 1 - math.exp(-2 * math.pi * 220 / RATE)
    samples = []
    for n in range(round(RATE * LENGTH)):
        t = n / RATE
        white = noise.uniform(-1, 1)
        fast += high * (white - fast)
        slow += low * (white - slow)
        band = fast - slow
        attack = min(1.0, t / 0.0008)
        attack = attack * attack * (3 - 2 * attack)
        envelope = attack * math.exp(-t / 0.0048)
        contact = max(0.0, t - 0.007)
        second = (1 - math.exp(-contact / 0.0005)) * math.exp(-contact / 0.0025) if t > 0.007 else 0
        body = math.sin(2 * math.pi * 820 * t) * math.exp(-t / 0.0038) * attack
        signal = 0.8 * band * envelope + 0.22 * body + 0.22 * band * second
        fade = min(1.0, max(0.0, (LENGTH - t) / 0.006))
        samples.append(signal * fade * fade)
    gain = PEAK / max(map(abs, samples))
    pcm = [round(value * gain * 32767) for value in samples]
    pcm[0] = pcm[-1] = 0
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(RATE)
        output.writeframes(struct.pack("<" + "h" * len(pcm), *pcm))
    wav = buffer.getvalue()
    (ROOT / "assets/tally-click.wav").write_bytes(wav)
    lines = [
        "// Copyright (c) 2026 davoda1. Generated by packaging/make_click_sound.py.",
        "// SPDX-License-Identifier: Zlib",
        "// Original 35 ms quiet mechanical click; peak level is -23.7 dBFS.",
        "#pragma once", "#include <array>", "#include <cstdint>",
        "namespace tally::click_sound {", f"inline constexpr unsigned sampleRate={RATE};",
        f"inline constexpr std::array<std::int16_t,{len(pcm)}> pcm={{{{",
    ]
    for start in range(0, len(pcm), 20):
        lines.append("    " + ",".join(map(str, pcm[start:start+20])) + ",")
    lines += ["}};", f"alignas(4) inline constexpr std::array<unsigned char,{len(wav)}> wav={{{{"]
    for start in range(0, len(wav), 24):
        lines.append("    " + ",".join(map(str, wav[start:start+24])) + ",")
    lines += ["}};", "}", ""]
    (ROOT / "src/click_sound.hpp").write_text("\n".join(lines), encoding="utf-8")
    rms = math.sqrt(sum((value / 32768)**2 for value in pcm) / len(pcm))
    print(f"Generated {len(pcm)} samples, {LENGTH*1000:g} ms, peak {PEAK:g}, RMS {20*math.log10(rms):.1f} dBFS")


if __name__ == "__main__":
    main()
